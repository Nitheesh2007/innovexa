function escapeRegExp(string) {
  return string.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}

/**
 * Robust string translator
 */
export function translateString(str) {
  if (!str || typeof str !== 'string') return str;
  const trimmed = str.trim();
  if (!trimmed) return str;

  // 1. Direct exact match
  if (translations[trimmed]) {
    const leadingWs = str.match(/^\s*/)[0];
    const trailingWs = str.match(/\s*$/)[0];
    return leadingWs + translations[trimmed] + trailingWs;
  }

  // 2. Case-insensitive exact match
  const lowerCore = trimmed.toLowerCase();
  if (lowerTranslations.has(lowerCore)) {
    const leadingWs = str.match(/^\s*/)[0];
    const trailingWs = str.match(/\s*$/)[0];
    return leadingWs + lowerTranslations.get(lowerCore) + trailingWs;
  }

  // 3. Punctuation & symbol peeling (e.g. "Total:", "(SKU)", "Price:", "Cost: ₹", etc.)
  const leadingPunctMatch = str.match(/^[\s\(\[\{\-•·\*\:\,\#]*/)[0];
  const trailingPunctMatch = str.match(/[\s\:\,\.\!\?\)\]\}\-\•]*$/)[0];
  if (leadingPunctMatch.length > 0 || trailingPunctMatch.length > 0) {
    const cleanCore = str.slice(leadingPunctMatch.length, str.length - trailingPunctMatch.length).trim();
    if (cleanCore) {
      if (translations[cleanCore]) {
        return leadingPunctMatch + translations[cleanCore] + trailingPunctMatch;
      }
      if (lowerTranslations.has(cleanCore.toLowerCase())) {
        return leadingPunctMatch + lowerTranslations.get(cleanCore.toLowerCase()) + trailingPunctMatch;
      }
    }
  }

  // 4. Pattern replacements (numbers + units)
  let replaced = str
    .replace(/(\d+)\s+units?\s+inward/gi, '$1 அலகுகள் உள்ளே')
    .replace(/(\d+)\s+units?\s+outward/gi, '$1 அலகுகள் வெளியே')
    .replace(/(\d+)\s+units?/gi, '$1 அலகுகள்')
    .replace(/(\d+)\s+records?/gi, '$1 பதிவுகள்')
    .replace(/(\d+)\s+items?/gi, '$1 பொருட்கள்')
    .replace(/\/\s*(\d+)\s+low/gi, '/ $1 குறைவு')
    .replace(/(\d+)\s+days?\s+ago/gi, '$1 நாட்களுக்கு முன்')
    .replace(/(\d+)\s+hours?\s+ago/gi, '$1 மணிநேரங்களுக்கு முன்')
    .replace(/(\d+)\s+minutes?\s+ago/gi, '$1 நிமிடங்களுக்கு முன்');

  // 5. Multi-phrase replacement (longest phrases first, avoiding regex stateful lastIndex bugs)
  for (const key of sortedTranslationKeys) {
    if (key.length >= 3 && replaced.toLowerCase().includes(key.toLowerCase())) {
      const val = translations[key];
      // Case-insensitive boundary replacement
      const reg = new RegExp(`(?<=^|[^A-Za-z0-9])${escapeRegExp(key)}(?=$|[^A-Za-z0-9])`, 'gi');
      replaced = replaced.replace(reg, val);
    }
  }

  return replaced;
}


module.exports = { translations, translateString };
